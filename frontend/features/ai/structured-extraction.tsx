"use client";

import { useState } from "react";
import { Braces } from "lucide-react";

import { ErrorState } from "@/components/states";
import { Button, LoadingButton } from "@/components/ui/button";
import { Dialog, DialogContent, DialogDescription, DialogFooter, DialogHeader, DialogTitle } from "@/components/ui/dialog";
import { Label } from "@/components/ui/label";
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from "@/components/ui/select";
import { Textarea } from "@/components/ui/textarea";
import { useStructuredExtraction } from "@/features/ai/hooks";

const OUTPUT_SCHEMAS = {
  outline: {
    type: "object",
    properties: {
      summary: { type: "string", description: "A concise summary of the requested topic" },
      keyPoints: { type: "array", items: { type: "string" } },
      reviewQuestions: { type: "array", items: { type: "string" } },
    },
    required: ["summary", "keyPoints", "reviewQuestions"],
    additionalProperties: false,
  },
  flashcards: {
    type: "object",
    properties: {
      flashcards: {
        type: "array",
        items: {
          type: "object",
          properties: {
            question: { type: "string" },
            answer: { type: "string" },
          },
          required: ["question", "answer"],
          additionalProperties: false,
        },
      },
    },
    required: ["flashcards"],
    additionalProperties: false,
  },
} as const;

export function StructuredExtractionDialog() {
  const [open, setOpen] = useState(false);
  const [prompt, setPrompt] = useState("");
  const [shape, setShape] = useState<keyof typeof OUTPUT_SCHEMAS>("outline");
  const extraction = useStructuredExtraction();

  const runExtraction = () => {
    const text = prompt.trim();
    if (!text) return;
    extraction.mutate({ prompt: text, schema: OUTPUT_SCHEMAS[shape], ground: true });
  };

  return (
    <>
      <Button variant="outline" size="sm" onClick={() => setOpen(true)} aria-label="Open structured study extraction" className="max-sm:h-11 max-sm:w-11 max-sm:px-0">
        <Braces className="h-4 w-4" aria-hidden />
        <span className="hidden 2xl:inline">Extract</span>
      </Button>
      <Dialog
        open={open}
        onOpenChange={(next) => {
          setOpen(next);
          if (!next) extraction.reset();
        }}
      >
        <DialogContent className="max-w-2xl">
          <DialogHeader>
            <DialogTitle>Structured study extraction</DialogTitle>
            <DialogDescription>
              Ask the assistant to organize study information into a validated outline or flashcards. It can ground the result in your StudentOS academic records; it will not create or change records.
            </DialogDescription>
          </DialogHeader>
          <div className="space-y-4">
            <div className="space-y-2">
              <Label htmlFor="structured-output-shape">Output format</Label>
              <Select value={shape} onValueChange={(value) => setShape(value as keyof typeof OUTPUT_SCHEMAS)}>
                <SelectTrigger id="structured-output-shape"><SelectValue /></SelectTrigger>
                <SelectContent>
                  <SelectItem value="outline">Study outline</SelectItem>
                  <SelectItem value="flashcards">Flashcards</SelectItem>
                </SelectContent>
              </Select>
            </div>
            <div className="space-y-2">
              <Label htmlFor="structured-prompt">What should it organize?</Label>
              <Textarea
                id="structured-prompt"
                rows={3}
                maxLength={4000}
                value={prompt}
                onChange={(event) => setPrompt(event.target.value)}
                placeholder="For example: Make review questions for my upcoming biology exam on cell structure."
              />
            </div>
            {extraction.isError && <ErrorState error={extraction.error} retry={runExtraction} />}
            {extraction.data && (
              <div className="space-y-2">
                <p className="text-sm text-muted-foreground">
                  Generated by {extraction.data.provider}{extraction.data.model ? ` · ${extraction.data.model}` : ""}
                  {extraction.data.repaired ? " · output validated after correction" : ""}
                </p>
                <pre className="max-h-72 overflow-auto rounded-md border border-border bg-muted/40 p-3 text-xs leading-relaxed">
                  {JSON.stringify(extraction.data.result, null, 2)}
                </pre>
              </div>
            )}
          </div>
          <DialogFooter>
            <Button variant="ghost" onClick={() => setOpen(false)}>Close</Button>
            <LoadingButton loading={extraction.isPending} disabled={!prompt.trim()} onClick={runExtraction}>
              Extract
            </LoadingButton>
          </DialogFooter>
        </DialogContent>
      </Dialog>
    </>
  );
}
